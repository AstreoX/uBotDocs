// Helpers shared by the reference framework (lib/reference/index.mjs) and its providers.
import { esc, firstParagraph } from "../blueprint/render.mjs";

export { esc };

export const GENERATED = (source) => `<!-- Generated by scripts/gen-reference.mjs from ${source}. Do not edit: change the data and run npm run gen. -->`;

/** Escapes Markdown punctuation in heading text. */
export const mdText = (s) => String(s).replace(/[{}]/g, "").replace(/([\\`*_[\]<>#|])/g, "\\$1");
export const yamlStr = (s) => JSON.stringify(String(s ?? ""));

export function frontmatter({ title, description, label, order }) {
  const lines = ["---", `title: ${yamlStr(title)}`];
  if (description) lines.push(`description: ${yamlStr(description)}`);
  lines.push("sidebar:");
  if (label) lines.push(`  label: ${yamlStr(label)}`);
  lines.push(`  order: ${order}`);
  lines.push("editUrl: false", "---", "");
  return lines.join("\n");
}

/** Description for frontmatter: first sentence of a summary, short. */
export function shortDescription(text) {
  const t = firstParagraph(text);
  if (!t) return "";
  const m = /^(.+?[。．.!?！？])(\s|$)/.exec(t);
  const s = (m ? m[1] : t).trim();
  return s.length > 160 ? `${s.slice(0, 157)}…` : s;
}

export const byName = (a, b) => a.localeCompare(b, "en", { sensitivity: "base", numeric: true }) || (a < b ? -1 : a > b ? 1 : 0);

/** A two-column metadata list (`<dl class="ref-meta">`) from [[label, html]] rows. */
export const metaList = (rows) => `<dl class="ref-meta">${rows.map(([dt, dd]) => `<dt>${esc(dt)}</dt><dd>${dd}</dd>`).join("")}</dl>`;

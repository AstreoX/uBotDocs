test("package home pages and the overview come from data/index.json", () => {
  execFileSync(process.execPath, [join(root, "scripts", "gen-reference.mjs")], { cwd: root, stdio: "pipe" });
  const ref = join(root, "src", "content", "docs", "reference");
  const packages = repoPackages();
  const has = (text, fragment) => assert.ok(text.includes(fragment), `expected ${JSON.stringify(fragment)}`);

  const pkg = packages.get("UBotSensor"); // the package the sample pages are about
  const sensor = readFileSync(join(ref, "ubotsensor", "index.md"), "utf8");
  has(sensor, "<dt>层级</dt><dd>能力（Capability）</dd>");
  has(sensor, `<dt>文档版本</dt><dd>${pkg.documentedVersion}（UE `);
  for (const r of pkg.requires) has(sensor, `<a href="${packages.get(r.name).path}">${r.name}</a>`);
  has(sensor, `<dt>预编译</dt><dd>${pkg.prebuilt.map((b) => `UE ${b.engine} ${b.platform}`).join("、")}</dd>`);
  assert.match(sensor, /## 相关指南 \{#guides\}[\s\S]*\/guides\/sensors\/imu-orientation\//, "the IMU guide declares UBotSensor through guides/sensors/_group.yml");
  assert.match(sensor, /## 类 \{#classes\}/);
  assert.ok(!existsSync(join(ref, "ubotsensor", "_group.yml")), "package groups are built in astro.config.mjs");

  // every released package has a page; planned ones only a row in the planned table
  const overview = readFileSync(join(ref, "index.md"), "utf8");
  for (const p of packages.released()) {
    assert.ok(existsSync(join(ref, p.slug, "index.md")), `${p.name} has a home page`);
    has(overview, `<a href="${p.path}">${p.name}</a><span class="ref-sub">${p.friendlyName}</span>`);
  }
  const planned = packages.planned();
  if (planned.length) assert.match(overview, /## 规划中 \{#planned\}/);
  else assert.doesNotMatch(overview, /规划中/);
  for (const p of planned) {
    has(overview, `<td>${p.name}<span class="ref-sub">${p.friendlyName}</span></td><td>${p.layerLabel}</td>`);
    assert.doesNotMatch(overview, new RegExp(`href="/reference/${p.slug}/`), `${p.name} is planned: no link`);
    assert.ok(!existsSync(join(ref, p.slug)), `${p.name} is planned: no page`);
  }

  const nodes = readFileSync(join(ref, "nodes.md"), "utf8");
  const options = packages.released().map((p) => `<option value="${p.name}">${p.name}</option>`).join("");
  has(nodes, `<select aria-label="按插件过滤" data-node-package="node-index"><option value="">全部插件</option>${options}<option value="Engine">UE 引擎</option></select>`);
  assert.match(nodes, /data-package="UBotSensor"><td>/);
});

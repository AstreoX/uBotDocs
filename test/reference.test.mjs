import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { repoPackages, root } from "./helpers.mjs";

test("gen-reference writes class, struct, enum, index and engine pages with stable anchors", () => {
  execFileSync(process.execPath, [join(root, "scripts", "gen-reference.mjs")], { cwd: root, stdio: "pipe" });
  const ref = join(root, "src", "content", "docs", "reference");
  for (const f of ["index.md", "nodes.md", "engine.md", "ubotsensor/index.md", "ubotsensor/uubotimusensorcomponent.md", "ubotsensor/structs/fubotimusensordata.md", "ubotcore/enums/eubotsamplestatus.md"]) {
    assert.ok(existsSync(join(ref, f)), f);
  }
  const imu = readFileSync(join(ref, "ubotsensor", "uubotimusensorcomponent.md"), "utf8");
  assert.match(imu, /^### Get Latest IMUData \{#GetLatestIMUData\}$/m);
  assert.match(imu, /^### On Imu Data Updated \{#OnImuDataUpdated\}$/m);
  assert.match(imu, /Generated by scripts\/gen-reference\.mjs/);
  assert.match(imu, /返回最近一次采样的 IMU 数据副本/, "Chinese summary from data/zh");
  assert.match(imu, /<tr id="prop-UpdateRateHz">.*继承.*父类默认/, "inherited property with a different default");
  const sensorRef = repoPackages().get("UBotSensor").documented.ref;
  assert.ok(imu.includes(`https://github.com/AstreoX/uBotSensor/blob/${sensorRef}/Source/UBotSensor/Public/UBotImuSensorComponent.h`), "source links point at the documented version's tag");
  const engine = readFileSync(join(ref, "engine.md"), "utf8");
  assert.match(engine, /\{#UKismetMathLibrary-Quat_Rotator\}/);
  const nodes = readFileSync(join(ref, "nodes.md"), "utf8");
  assert.match(nodes, /data-node-filter="node-index"/);
  assert.match(nodes, /href="\/reference\/ubotsensor\/uubotimusensorcomponent\/#GetLatestIMUData"/);
});

test("property tables state the common access once and mark only the exceptions", () => {
  execFileSync(process.execPath, [join(root, "scripts", "gen-reference.mjs")], { cwd: root, stdio: "pipe" });
  const ref = join(root, "src", "content", "docs", "reference");
  const imu = readFileSync(join(ref, "ubotsensor", "uubotimusensorcomponent.md"), "utf8");
  assert.match(imu, /<p class="ref-legend">未特别标注的属性：蓝图里只读，Details 面板里可以编辑。<\/p>/);
  assert.doesNotMatch(imu, /蓝图只读，Details 可编辑/, "the common access is not repeated on every row");
  // a property that differs from the common access keeps its own note
  const settings = readFileSync(join(ref, "ubotcore", "uubotcoresettings.md"), "utf8");
  assert.match(settings, /蓝图不可访问，Details 可编辑/, "exceptions are still marked");
});


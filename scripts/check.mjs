#!/usr/bin/env node
// npm run check: validates data/index.json, data/api, data/zh, data/engine-nodes, every ```blueprint
// block, the packages pages declare and the writing rules.
// Errors fail (exit 1); warnings are printed and do not fail. Runs in CI on every pull request.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadSite } from "../lib/blueprint/site.mjs";
import { loadPackages } from "../lib/packages.mjs";
import { LEGACY_ENGINE_LIST, checkEngineLists, readEngineLists } from "../lib/engine-nodes.mjs";
import { checkContent, checkLockfile, formatFinding, githubAnnotation, GENERATED_DIR } from "../lib/check.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const quiet = process.argv.includes("--quiet");
const packages = loadPackages({ root });
const site = loadSite(root);
const findings = [...packages.diagnostics, ...site.diagnostics, ...checkContent(root, site.registry, { packages: packages.registry })];

findings.push(...checkEngineLists(readEngineLists(join(root, "data"))));
if (existsSync(join(root, LEGACY_ENGINE_LIST))) {
  findings.push({ severity: "error", file: LEGACY_ENGINE_LIST, line: 1, message: "engine node lists moved to data/engine-nodes/<area>.txt; move these entries to data/engine-nodes/core.txt (or the file of their area) and delete this file" });
}

const lockfile = join(root, "package-lock.json");
if (existsSync(lockfile)) findings.push(...checkLockfile("package-lock.json", readFileSync(lockfile, "utf8")));

// The generated reference is rebuilt from scratch by gen-reference; hand-written files there are lost.
try {
  const tracked = execFileSync("git", ["ls-files", GENERATED_DIR], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  for (const f of tracked ? tracked.split("\n") : []) {
    findings.push({ severity: "error", file: f, line: 1, message: `${GENERATED_DIR}/ is generated by scripts/gen-reference.mjs; do not commit files there (Chinese summaries go to data/zh/<Package>/<Owner>.yaml)` });
  }
} catch {
  // not a git checkout: nothing to compare
}

const order = { error: 0, warning: 1 };
findings.sort((a, b) => order[a.severity] - order[b.severity] || (a.file < b.file ? -1 : a.file > b.file ? 1 : a.line - b.line));
const errors = findings.filter((d) => d.severity === "error");
const warnings = findings.filter((d) => d.severity === "warning");
for (const d of findings) {
  if (quiet && d.severity === "warning") continue;
  console.log(formatFinding(d));
}
if (process.env.GITHUB_ACTIONS === "true") for (const d of findings) console.log(githubAnnotation(d));
console.log(`\ncheck: ${errors.length} error(s), ${warnings.length} warning(s)`);
process.exit(errors.length ? 1 : 0);
